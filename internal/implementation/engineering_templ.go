package implementation

import (
	"context"
	"errors"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"

	"github.com/berryhill/aegis/internal/loop"
	"golang.org/x/mod/modfile"
)

const templTool = "github.com/a-h/templ/cmd/templ"

var errTemplConsistency = errors.New("selected template/generated source consistency not established")

// Paths derive from the sealed issue selection, never a command or generator
// supplied by the issue. Existing paired Go output must be separately writable;
// no global regeneration, implied authority expansion or extra output is allowed.
func selectedTemplPairs(paths []string) []string {
	seen := map[string]bool{}
	for _, p := range paths {
		if strings.HasSuffix(p, ".templ") {
			seen[p] = true
		}
		if strings.HasSuffix(p, "_templ.go") {
			seen[strings.TrimSuffix(p, "_templ.go")+".templ"] = true
		}
	}
	out := []string{}
	for p := range seen {
		out = append(out, p)
	}
	sort.Strings(out)
	return out
}
func templOutput(p string) string { return strings.TrimSuffix(p, ".templ") + "_templ.go" }

// Match go:generate's package-directory convention: templ embeds its -f value
// in generated error metadata. Keep module discovery in the private source tree
// and the caller's pinned offline environment, but select only this basename.
func scopedTemplCommand(driver, workspace, input string, env []string, check bool) *exec.Cmd {
	args := []string{"run", templTool, "generate", "-f", filepath.Base(input)}
	if check {
		args = append(args, "-check")
	}
	args = append(args, "-include-timestamp=false", "-include-version=true")
	cmd := exec.Command(driver, args...)
	cmd.Dir = filepath.Join(workspace, filepath.Dir(input))
	cmd.Env = append([]string(nil), env...)
	return cmd
}

func validateTemplSelection(c loop.VerifiedImplementation, p loop.ContributionExecutionPolicy) error {
	pairs := selectedTemplPairs(c.WritableFiles)
	if len(pairs) == 0 {
		return nil
	}
	if c.SchemaVersion != loop.RepositoryEngineeringSchema || p.TemplConsistency != loop.TemplModuleConsistency || p.Dependencies == nil || c.RepositoryContext == nil {
		return errTemplConsistency
	}
	files := map[string]bool{}
	writable := map[string]bool{}
	for _, f := range c.RepositoryContext.Files {
		files[f.Path] = !f.Absent
	}
	for _, f := range c.WritableFiles {
		writable[f] = true
	}
	for _, input := range pairs {
		if !files[input] || !files[templOutput(input)] || !writable[templOutput(input)] {
			return errTemplConsistency
		}
	}
	return nil
}

// Check exact pinned tool declaration and dependency. Tool packages are not a
// general execution permission: only this literal module tool is supported.
func pinnedTemplModule(source SourceInventory) error {
	for _, f := range source.Files {
		if f.Path != "go.mod" {
			continue
		}
		m, err := modfile.Parse("go.mod", f.Content, nil)
		if err != nil || len(m.Replace) > 0 || len(m.Exclude) > 0 {
			return errTemplConsistency
		}
		tool, pinned := false, false
		for _, t := range m.Tool {
			tool = tool || t.Path == templTool
		}
		for _, r := range m.Require {
			pinned = pinned || (r.Mod.Path == "github.com/a-h/templ" && r.Mod.Version != "")
		}
		if tool && pinned {
			return nil
		}
	}
	return errTemplConsistency
}

// Execute read-only deterministic generation checking in the materialized
// private full-source copy under the same pinned native operation and offline
// environment. No repository generator, shell, network or writing flags exist.
// The pinned tool's check writer compares exact generated bytes. Stdout mode is
// unsuitable: the tool emits no output when existing bytes already match.
func checkTemplConsistency(ctx context.Context, driver, workspace string, env []string, source SourceInventory, pairs []string, run func(context.Context, *exec.Cmd) error) error {
	if len(pairs) == 0 {
		return nil
	}
	if pinnedTemplModule(source) != nil {
		return errTemplConsistency
	}
	files := map[string][]byte{}
	for _, f := range source.Files {
		files[f.Path] = f.Content
	}
	for _, input := range pairs {
		if !loop.SafeRepositoryContextPath(input) || files[input] == nil || files[templOutput(input)] == nil {
			return errTemplConsistency
		}
		cmd := scopedTemplCommand(driver, workspace, input, env, true)
		var output, diagnostic boundedOutput
		cmd.Stdout, cmd.Stderr = &output, &diagnostic
		if err := run(ctx, cmd); err != nil {
			return errors.Join(errTemplConsistency, err)
		}
		if output.overflow || diagnostic.overflow {
			return errTemplConsistency
		}
	}
	return nil
}
