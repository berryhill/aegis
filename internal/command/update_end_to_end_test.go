// Only the service-manager protocol is synthetic. Each activation execs a real
// release-shaped Aegis binary with a private config; readiness, audit, Console,
// authenticated Agent reads and /proc executable identity are production paths.
// No fixture implements an HTTP readiness response or invokes systemctl.
type upgradeProcessRunner struct {
	plan       userservice.Plan
	child      *exec.Cmd
	done       chan error
	calls      [][]string
	failStart  bool
	stalePath  string
	interrupt  context.CancelFunc
	failReload bool
}

func (r *upgradeProcessRunner) stop() error {
	if r.child == nil {
		return nil
	}
	_ = r.child.Process.Signal(syscall.SIGTERM)
	select {
	case <-r.done:
	case <-time.After(8 * time.Second):
		_ = r.child.Process.Kill()
		<-r.done
		return errors.New("owned gateway did not terminate gracefully")
	}
	r.child = nil
	return nil
}
func (r *upgradeProcessRunner) Run(_ context.Context, args ...string) error {
	r.calls = append(r.calls, append([]string(nil), args...))
	if len(args) == 1 && args[0] == "daemon-reload" {
		if r.failReload {
			return errors.New("injected exact unit migration reload failure")
		}
		return nil
	}
	if len(args) == 3 && args[0] == "enable" && args[1] == "--now" && args[2] == userservice.UnitName {
		return r.Run(context.Background(), "start", userservice.UnitName)
	}
	if len(args) != 2 || args[1] != userservice.UnitName {
		return fmt.Errorf("unowned service action: %q", args)
	}
	switch args[0] {
	case "stop":
		return r.stop()
	case "start":
		if r.failStart {
			if r.interrupt != nil {
				r.interrupt()
			}
			return errors.New("injected startup interruption after replacement")
		}
		binary := r.plan.Executable
		if r.stalePath != "" {
			binary = r.stalePath
		}
		r.child = exec.Command(binary, "serve", "--config", r.plan.ConfigPath)
		// Do not use a bytes.Buffer concurrently with the subprocess copy goroutines.
		r.child.Stdout = io.Discard
		r.child.Stderr = io.Discard
		if err := r.child.Start(); err != nil {
			r.child = nil
			return err
		}
		r.done = make(chan error, 1)
		child, done := r.child, r.done
		go func() { done <- child.Wait() }()
		return nil
	default:
		return fmt.Errorf("unexpected service action: %q", args)
	}
}
func (r *upgradeProcessRunner) Output(_ context.Context, args ...string) ([]byte, error) {
	r.calls = append(r.calls, append([]string(nil), args...))
	if len(args) != 5 || args[0] != "show" || args[1] != userservice.UnitName || args[2] != "--property" || args[4] != "--value" {
		return nil, fmt.Errorf("unowned service query: %q", args)
	}
	value := ""
	switch args[3] {
	case "ActiveState":
		value = "inactive"
		if r.child != nil {
			value = "active"
		}
	case "UnitFileState":
		value = "disabled"
	case "FragmentPath":
		value = r.plan.UnitPath
	case "ExecStart":
		value = fmt.Sprintf("{ path=%s ; argv[]=%s serve --config %s ; ignore_errors=no ; start_time=[n/a] ; stop_time=[n/a] ; pid=0 ; code=(null) ; status=0/0 }", r.plan.Executable, r.plan.Executable, r.plan.ConfigPath)
	case "MainPID":
		value = "0"
		if r.child != nil {
			value = strconv.Itoa(r.child.Process.Pid)
		}
	default:
		return nil, fmt.Errorf("unexpected property %q", args[3])
	}
	return []byte(value + "\n"), nil
}

type upgradeCommandFixture struct {
	path, state, target, old string
	runner                   *upgradeProcessRunner
	updater                  *selfupdate.Updater
}

type unavailableUpgradeInput struct{}

func (*unavailableUpgradeInput) Acquire(context.Context, AuthorityPassphraseRequest) ([]byte, error) {
	return nil, &PassphraseError{Kind: PassphraseUnavailable, reason: "synthetic protected input unavailable"}
}

func installLegacyUpgradeFixture(t *testing.T, f *upgradeCommandFixture) {
	t.Helper()
	cfg, err := config.Load(f.path, nil)
	if err != nil {
		t.Fatal(err)
	}
	unit := fmt.Sprintf("# Generated by Aegis; digest-bound user service.\n[Unit]\nDescription=Aegis authenticated local control plane\nAfter=network.target\n\n[Service]\nType=simple\nExecStart=%s serve --config %s\nRestart=on-failure\nRestartSec=2s\nTimeoutStopSec=%s\nKillMode=control-group\nKillSignal=SIGTERM\nUMask=0077\nNoNewPrivileges=true\n\n[Install]\nWantedBy=default.target\n", strconv.Quote(f.target), strconv.Quote(f.path), cfg.API.ShutdownTimeout)
	sum := sha256.Sum256([]byte(unit))
	if fmt.Sprintf("%x", sum) != f.runner.plan.LegacyUnitDigest {
		t.Fatal("fixture is not the recognized historical unit")
	}
	upgradeWrite(t, f.runner.plan.UnitPath, []byte(unit), 0600)
}

func upgradeReleaseBuild(t *testing.T, dir, version string) string {
	t.Helper()
	path := filepath.Join(dir, "aegis-"+version)
	ctx, cancel := context.WithTimeout(context.Background(), 90*time.Second)
	defer cancel()
	flags := "-s -w -X github.com/berryhill/aegis/internal/buildinfo.Version=" + version + " -X github.com/berryhill/aegis/internal/buildinfo.SourceRevision=" + strings.Repeat("a", 40)
	cmd := exec.CommandContext(ctx, "go", "build", "-buildvcs=false", "-ldflags", flags, "-o", path, "./cmd/aegis")
	cmd.Dir = filepath.Join("..", "..")
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("build release fixture: %v\n%s", err, out)
	}
	return path
}
func upgradeWrite(t *testing.T, path string, b []byte, mode os.FileMode) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0700); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, b, mode); err != nil {
		t.Fatal(err)
	}
}
func newUpgradeCommandFixture(t *testing.T, old, candidate string) *upgradeCommandFixture {
	return newVersionedUpgradeCommandFixture(t, old, candidate, "0.2.29")
}
func newVersionedUpgradeCommandFixture(t *testing.T, old, candidate, releaseVersion string) *upgradeCommandFixture {
	t.Helper()
	path, state := validConfigWithoutOperationalAuthority(t)
	home := filepath.Dir(path)
	t.Setenv("HOME", home)
	t.Setenv("XDG_CONFIG_HOME", filepath.Join(home, "xdg"))
	t.Setenv("XDG_STATE_HOME", filepath.Join(home, "xdg-state"))
	t.Setenv("XDG_DATA_HOME", filepath.Join(home, "xdg-data"))
	socketRoot, err := os.MkdirTemp("", "aegis-upgrade-")
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = os.RemoveAll(socketRoot) })
	listener, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		t.Fatal(err)
	}
	addr := listener.Addr().String()
	_ = listener.Close()
	token := filepath.Join(home, "api.token")
	upgradeWrite(t, token, []byte(strings.Repeat("e", 64)), 0600)
	data := mustCommandRead(t, path)
	data = append(data, []byte(fmt.Sprintf("api:\n  listen: %q\n  token_file: %q\n  unix_socket: %q\n  console:\n    origin: %q\n", addr, token, filepath.Join(socketRoot, "a.sock"), "http://"+addr))...)
	upgradeWrite(t, path, data, 0600)
	if _, err = authoritybadger.Initialize(context.Background(), filepath.Join(state, "persistence", "authority-v1")); err != nil {
		t.Fatal(err)
	}
	verifier, err := principalauth.Enroll("principal", []byte("synthetic-recovery-password"))
	if err != nil {
		t.Fatal(err)
	}
	if err = principalauth.Publish(filepath.Join(state, "auth", principalauth.FileName), verifier); err != nil {
		t.Fatal(err)
	}
	target := filepath.Join(home, "bin", "aegis")
	upgradeWrite(t, target, mustCommandRead(t, old), 0700)
	plan, err := userservice.Preview(target, path)
	if err != nil {
		t.Fatal(err)
	}
	runner := &upgradeProcessRunner{plan: plan}
	t.Cleanup(func() {
		if err := runner.stop(); err != nil {
			t.Error(err)
		}
	})
	// Apply the production renderer and observe a real ready process before
	// stopping it to establish the already-installed fixture.
	if err = userservice.Apply(context.Background(), plan, runner, 10*time.Second); err != nil {
		t.Fatal(err)
	}
	if err = runner.stop(); err != nil {
		t.Fatal(err)
	}
	runner.calls = nil
	var archive bytes.Buffer
	gz, err := gzip.NewWriterLevel(&archive, gzip.BestSpeed)
	if err != nil {
		t.Fatal(err)
	}
	tw := tar.NewWriter(gz)
	binary := mustCommandRead(t, candidate)
	if err = tw.WriteHeader(&tar.Header{Name: "aegis", Mode: 0755, Size: int64(len(binary))}); err != nil {
		t.Fatal(err)
	}
	if _, err = tw.Write(binary); err != nil {
		t.Fatal(err)
	}
	if err = tw.Close(); err != nil {
		t.Fatal(err)
	}
	if err = gz.Close(); err != nil {
		t.Fatal(err)
	}
	asset := fmt.Sprintf("aegis_v%s_%s_%s.tar.gz", releaseVersion, runtime.GOOS, runtime.GOARCH)
	sum := sha256.Sum256(archive.Bytes())
	var server *httptest.Server
	server = httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		switch r.URL.Path {
		case "/latest":
			_ = json.NewEncoder(w).Encode(map[string]any{"tag_name": "v" + releaseVersion, "html_url": server.URL + "/releases/tag/v" + releaseVersion, "published_at": "2026-10-01T00:00:00Z"})
		case "/download/v" + releaseVersion + "/SHA256SUMS":
			fmt.Fprintf(w, "%x  %s\n", sum, asset)
		case "/download/v" + releaseVersion + "/" + asset:
			_, _ = w.Write(archive.Bytes())
		default:
			http.NotFound(w, r)
		}
	}))
	t.Cleanup(server.Close)
	updater := selfupdate.New("0.2.28")
	updater.APIURL = server.URL + "/latest"
	updater.DownloadURL = server.URL + "/download"
	updater.RepositoryURL = server.URL
	updater.Client = server.Client()
	updater.Executable = func() (string, error) { return target, nil }
	return &upgradeCommandFixture{path: path, state: state, target: target, old: old, runner: runner, updater: updater}
}
func (f *upgradeCommandFixture) run(t *testing.T, ctx context.Context, provider AuthorityPassphraseProvider) (selfupdate.Result, error) {
	t.Helper()
	var out bytes.Buffer
	cmd := &cobra.Command{}
	cmd.SetContext(context.WithValue(ctx, authorityPassphraseContextKey{}, provider))
	cmd.SetOut(&out)
	cmd.SetErr(io.Discard)
	err := runInstalledUpgrade(cmd, f.updater, f.runner, f.path)
	var result selfupdate.Result
	if e := json.Unmarshal(out.Bytes(), &result); e != nil {
		t.Fatalf("decode command result: %v", e)
	}
	if bytes.Contains(out.Bytes(), []byte("synthetic-recovery-password")) {
		t.Fatal("command leaked fixture secret")
	}
	return result, err
}

func TestInstalledUpgradeFullCommand(t *testing.T) {
	builds := t.TempDir()
	old := upgradeReleaseBuild(t, builds, "0.2.28")
	candidate := upgradeReleaseBuild(t, builds, "0.2.29")
	for _, scenario := range []string{"healthy", "current-cli-stopped", "already-stopped", "interrupted-authority", "legacy-unit", "migration-failure-resume", "cancelled-auth", "unavailable-auth", "startup-failure-resume", "socket-denial", "open-writer-denial", "stale-image", "journal-tamper", "journal-link", "journal-identity"} {
		t.Run(scenario, func(t *testing.T) {
			installed := old
			if scenario == "current-cli-stopped" {
				installed = candidate
			}
			f := newUpgradeCommandFixture(t, installed, candidate)
			if scenario == "current-cli-stopped" {
				f.updater.CurrentVersion = "0.2.29"
			}
			budget := 45 * time.Second
			if scenario == "open-writer-denial" {
				budget = 2 * time.Second
			}
			ctx, cancel := context.WithTimeout(context.Background(), budget)
			defer cancel()
			provider := &recoveryPasswordFixture{cancelled: scenario == "cancelled-auth"}
			root := filepath.Join(f.state, "persistence", "authority-v1")
			if scenario == "healthy" {
				if err := f.runner.Run(ctx, "start", userservice.UnitName); err != nil {
					t.Fatal(err)
				}
				deadline := time.Now().Add(10 * time.Second)
				for userservice.ObserveExactGateway(ctx, f.runner, f.runner.plan).State != userservice.GatewayHealthy {
					if time.Now().After(deadline) {
						t.Fatal("old real gateway never became ready")
					}
					time.Sleep(50 * time.Millisecond)
				}
				f.runner.calls = nil
			}
			if scenario == "interrupted-authority" {
				if err := os.Rename(filepath.Join(root, "CLEAN"), filepath.Join(root, "DIRTY")); err != nil {
					t.Fatal(err)
				}
			}
			if scenario == "socket-denial" {
				cfg, err := config.Load(f.path, nil)
				if err != nil {
					t.Fatal(err)
				}
				upgradeWrite(t, cfg.API.UnixSocket, []byte("preserve transport conflict"), 0600)
			}
			if scenario == "open-writer-denial" {
				store, err := authoritybadger.Open(ctx, root)
				if err != nil {
					t.Fatal(err)
				}
				defer store.Close()
			}
			if scenario == "startup-failure-resume" {
				f.runner.failStart = true
				f.runner.interrupt = cancel
			}
			if scenario == "stale-image" {
				f.runner.stalePath = old
			}
			if scenario == "legacy-unit" || scenario == "migration-failure-resume" {
				installLegacyUpgradeFixture(t, f)
				f.runner.failReload = scenario == "migration-failure-resume"
			}
			var auth AuthorityPassphraseProvider = provider
			if scenario == "unavailable-auth" {
				auth = &unavailableUpgradeInput{}
			}
			if strings.HasPrefix(scenario, "journal-") {
				prepared, err := f.updater.Prepare(ctx)
				if err != nil {
					t.Fatal(err)
				}
				id, err := prepared.Identity()
				prepared.Close()
				if err != nil {
					t.Fatal(err)
				}
				data := mustCommandRead(t, f.path)
				j, err := openUpgradeJournal(f.runner.plan, f.state, sha256.Sum256(data), id)
				if err != nil {
					t.Fatal(err)
				}
				if err = j.save(); err != nil {
					t.Fatal(err)
				}
				j.close()
				journal := filepath.Join(f.state, "upgrade", "journal.json")
				switch scenario {
				case "journal-tamper":
					upgradeWrite(t, journal, []byte("{}\n"), 0600)
				case "journal-link":
					if err = os.Link(journal, filepath.Join(f.state, "journal-alias")); err != nil {
						t.Fatal(err)
					}
				case "journal-identity":
					upgradeWrite(t, journal, bytes.ReplaceAll(mustCommandRead(t, journal), []byte(id.Digest), []byte(strings.Repeat("f", 64))), 0600)
				}
			}
			if scenario == "current-cli-stopped" {
				prepared, e := f.updater.Prepare(ctx)
				if e != nil {
					t.Fatal(e)
				}
				id, e := prepared.Identity()
				prepared.Close()
				if e != nil {
					t.Fatal(e)
				}
				j, e := openUpgradeJournal(f.runner.plan, f.state, sha256.Sum256(mustCommandRead(t, f.path)), id)
				if e != nil {
					t.Fatal(e)
				}
				j.receipt.Stage = "gateway_stop"
				if e = j.save(); e != nil {
					t.Fatal(e)
				}
				j.close()
				journalPath := filepath.Join(f.state, "upgrade", "journal.json")
				original := mustCommandRead(t, journalPath)
				var checked bytes.Buffer
				checkCmd := &cobra.Command{}
				checkCmd.SetContext(ctx)
				checkCmd.SetOut(&checked)
				checkCmd.SetErr(io.Discard)
				f.runner.calls = nil
				if e = runUpdate(checkCmd, f.updater, f.runner, userservice.ObserveExecutableImage, f.path, true); e != nil {
					t.Fatal(e)
				}
				var status selfupdate.Result
				if e = json.Unmarshal(checked.Bytes(), &status); e != nil {
					t.Fatal(e)
				}
				if status.UpdateAvailable || !status.ResumeRequired || status.Phase != "gateway_stop" || !status.GatewayRepairRequired || status.GatewayReadiness == string(userservice.GatewayHealthy) {
					t.Fatalf("dishonest current check: %+v", status)
				}
				if !bytes.Equal(original, mustCommandRead(t, journalPath)) {
					t.Fatal("check mutated journal")
				}
				for _, call := range f.runner.calls {
					if call[0] == "stop" || call[0] == "start" || call[0] == "daemon-reload" {
						t.Fatalf("check mutated lifecycle: %q", call)
					}
				}
			}
			before := sha256.Sum256(mustCommandRead(t, f.target))
			result, err := f.run(t, ctx, auth)
			success := scenario == "current-cli-stopped" || scenario == "healthy" || scenario == "already-stopped" || scenario == "interrupted-authority" || scenario == "legacy-unit"
			if success {
				if err != nil || !result.UpgradeComplete || result.ResumeRequired {
					t.Fatalf("real upgrade failed: result=%+v err=%v", result, err)
				}
				if image := userservice.ObserveExecutableImage(ctx, f.runner, f.target, f.path); image != "running_current_image" {
					t.Fatalf("kernel image=%s", image)
				}
			} else {
				if err == nil || result.UpgradeComplete {
					t.Fatalf("unsafe upgrade accepted: result=%+v err=%v", result, err)
				}
			}
			if scenario == "current-cli-stopped" {
				if userservice.ObserveExactGateway(ctx, f.runner, f.runner.plan).State != userservice.GatewayHealthy {
					t.Fatal("current CLI did not repair stopped gateway")
				}
				f.runner.calls = nil
				again, err := f.run(t, ctx, provider)
				if err != nil || !again.UpgradeComplete || again.ResumeRequired {
					t.Fatalf("healthy current retry: %+v %v", again, err)
				}
				for _, call := range f.runner.calls {
					if call[0] == "stop" || call[0] == "start" {
						t.Fatalf("healthy current retry mutated lifecycle: %q", call)
					}
				}
			}
			if strings.HasSuffix(scenario, "auth") {
				if before != sha256.Sum256(mustCommandRead(t, f.target)) {
					t.Fatal("authentication denial replaced binary")
				}
				for _, call := range f.runner.calls {
					if call[0] == "stop" || call[0] == "start" {
						t.Fatalf("authentication denial changed service: %q", call)
					}
				}
			}
			if scenario == "startup-failure-resume" {
				if f.runner.child != nil {
					t.Fatal("startup failure left child running")
				}
				journal := filepath.Join(f.state, "upgrade", "journal.json")
				saved := mustCommandRead(t, journal)
				if !bytes.Contains(saved, []byte("gateway_activation")) {
					t.Fatal("interruption stage was not persisted")
				}
				if before == sha256.Sum256(mustCommandRead(t, f.target)) {
					t.Fatal("interruption did not follow replacement")
				}
				f.runner.failStart = false
				f.runner.interrupt = nil
				f.updater.CurrentVersion = "0.2.29"
				resume, resumeCancel := context.WithTimeout(context.Background(), 45*time.Second)
				defer resumeCancel()
				result, err = f.run(t, resume, provider)
				if err != nil || !result.UpgradeComplete {
					t.Fatalf("real reentry failed: result=%+v err=%v", result, err)
				}
				if !bytes.Contains(mustCommandRead(t, journal), []byte("complete")) {
					t.Fatal("resumed journal not complete")
				}
			}
			if scenario == "migration-failure-resume" {
				if before != sha256.Sum256(mustCommandRead(t, f.target)) {
					t.Fatal("failed unit migration replaced the binary")
				}
				f.runner.failReload = false
				resume, resumeCancel := context.WithTimeout(context.Background(), 45*time.Second)
				defer resumeCancel()
				result, err = f.run(t, resume, provider)
				if err != nil || !result.UpgradeComplete {
					t.Fatalf("migration resumption failed: %+v %v", result, err)
				}
			}
		})
	}
}
