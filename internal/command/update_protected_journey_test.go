// Exercise the production retained-journey authentication and recovery methods,
// not a callback that assumes authentication. No terminal emulation is used.
func installedJourneyProtectedRecovery(t *testing.T) {
	if isolateCommandFixture(t) {
		return
	}
	for _, scenario := range []string{"healthy", "stopped-orphan", "missing-parent", "interrupted", "mismatched-clean", "socket", "cancelled", "verifier-drift", "config-drift", "expired", "recovery-deadline"} {
		t.Run(scenario, func(t *testing.T) {
			path, state := validConfigWithoutOperationalAuthority(t)
			b, err := os.ReadFile(path)
			if err != nil {
				t.Fatal(err)
			}
			token := filepath.Join(filepath.Dir(path), "token")
			if err = os.WriteFile(token, []byte("0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef"), 0600); err != nil {
				t.Fatal(err)
			}
			transport := filepath.Join(filepath.Dir(path), "transport")
			if err = os.Mkdir(transport, 0700); err != nil {
				t.Fatal(err)
			}
			socket := filepath.Join(transport, "gateway.sock")
			b = append(b, []byte(fmt.Sprintf("api:\n  token_file: %q\n  unix_socket: %q\n", token, socket))...)
			if err = os.WriteFile(path, b, 0600); err != nil {
				t.Fatal(err)
			}
			cfg, err := config.Load(path, nil)
			if err != nil {
				t.Fatal(err)
			}
			root := filepath.Join(state, "persistence", "authority-v1")
			if _, err = authoritybadger.Initialize(context.Background(), root); err != nil {
				t.Fatal(err)
			}
			if scenario == "interrupted" {
				if err = os.Rename(filepath.Join(root, "CLEAN"), filepath.Join(root, "DIRTY")); err != nil {
					t.Fatal(err)
				}
			}
			if scenario == "mismatched-clean" {
				if err = os.WriteFile(filepath.Join(root, "CLEAN"), []byte("{}\n"), 0600); err != nil {
					t.Fatal(err)
				}
			}
			if scenario == "stopped-orphan" {
				l, e := net.ListenUnix("unix", &net.UnixAddr{Name: socket, Net: "unix"})
				if e != nil {
					t.Fatal(e)
				}
				l.SetUnlinkOnClose(false)
				l.Close()
				if e = os.Chmod(socket, 0600); e != nil {
					t.Fatal(e)
				}
			}
			if scenario == "socket" {
				if err = os.WriteFile(socket, []byte("must remain"), 0600); err != nil {
					t.Fatal(err)
				}
			}
			verifier, err := recoveryPrincipalEnrollment()
			if err != nil {
				t.Fatal(err)
			}
			verifierPath := filepath.Join(state, "auth", principalauth.FileName)
			if err = principalauth.Publish(verifierPath, verifier); err != nil {
				t.Fatal(err)
			}
			executable, err := os.Executable()
			if err != nil {
				t.Fatal(err)
			}
			t.Setenv("XDG_CONFIG_HOME", filepath.Join(t.TempDir(), "config"))
			plan, err := userservice.Preview(executable, path)
			if err != nil {
				t.Fatal(err)
			}
			unit := "# Generated by Aegis; digest-bound user service.\n[Unit]\nDescription=Aegis authenticated local control plane\nAfter=network.target\n\n[Service]\nType=simple\nExecStart=" + strconv.Quote(executable) + " serve --config " + strconv.Quote(path) + "\nRestart=on-failure\nRestartSec=2s\nTimeoutStopSec=" + cfg.API.ShutdownTimeout.String() + "\nKillMode=control-group\nKillSignal=SIGTERM\nUMask=0077\nNoNewPrivileges=true\n\n[Install]\nWantedBy=default.target\n"
			if err = os.MkdirAll(filepath.Dir(plan.UnitPath), 0700); err != nil {
				t.Fatal(err)
			}
			if err = os.WriteFile(plan.UnitPath, []byte(unit), 0600); err != nil {
				t.Fatal(err)
			}
			provider := &recoveryPasswordFixture{cancelled: scenario == "cancelled"}
			cmd := &cobra.Command{}
			cmd.SetContext(context.WithValue(context.Background(), authorityPassphraseContextKey{}, provider))
			cmd.SetErr(io.Discard)
			journal, err := openUpgradeJournal(plan, state, sha256.Sum256(b), selfupdate.CandidateIdentity{Executable: executable, Version: "test", Source: "source", Digest: "digest"})
			if err != nil {
				t.Fatal(err)
			}
			defer journal.close()
			journal.receipt.PreviousUnitDigest = plan.LegacyUnitDigest
			j := &installedJourney{cmd: cmd, runner: &upgradeProcessRunner{plan: plan}, executable: executable, configPath: path, plan: plan, cfg: cfg, configDigest: sha256.Sum256(b), journal: journal}
			defer func() { clear(j.password) }()
			if scenario == "missing-parent" {
				if err = os.Chmod(filepath.Dir(path), 0700); err != nil {
					t.Fatal(err)
				}
				if err = os.Remove(transport); err != nil {
					t.Fatal(err)
				}
			}
			if scenario == "verifier-drift" {
				j.password = []byte("synthetic-recovery-password")
				j.verifier = verifier
				j.verifier.PrincipalID = "different"
				j.expires = time.Now().Add(time.Minute)
			}
			if scenario == "config-drift" {
				if err = os.WriteFile(path, append(b, []byte("# drift\n")...), 0600); err != nil {
					t.Fatal(err)
				}
			}
			if scenario == "expired" {
				j.password = []byte("expired")
				j.verifier = verifier
				j.expires = time.Now().Add(-time.Second)
			}
			if scenario == "recovery-deadline" {
				if err = j.admit(cmd.Context()); err != nil {
					t.Fatal(err)
				}
				store, openErr := authoritybadger.Open(context.Background(), root)
				if openErr != nil {
					t.Fatal(openErr)
				}
				defer store.Close()
				j.expires = time.Now().Add(250 * time.Millisecond)
				outer, cancel := context.WithTimeout(cmd.Context(), 2*time.Second)
				defer cancel()
				started := time.Now()
				originalExpiry, acquisitions := j.expires, provider.acquisitions
				remaining := time.Until(originalExpiry)
				err = j.Recover(outer)
				elapsed := time.Since(started)
				t.Logf("recovery_class elapsed_ns=%d deadline_match=%t cancelled_match=%t err_nil=%t original_remaining_ns=%d expires_changed=%t extra_acquisitions=%d outer_deadline=%t outer_cancelled=%t", elapsed.Nanoseconds(), errors.Is(err, context.DeadlineExceeded), errors.Is(err, context.Canceled), err == nil, remaining.Nanoseconds(), !j.expires.Equal(originalExpiry), provider.acquisitions-acquisitions, errors.Is(outer.Err(), context.DeadlineExceeded), errors.Is(outer.Err(), context.Canceled))
				if !errors.Is(err, context.DeadlineExceeded) || elapsed >= time.Second {
					t.Fatal("recovery exceeded retained authentication")
				}
				if _, err = os.Stat(filepath.Join(root, "recovery-evidence")); !errors.Is(err, os.ErrNotExist) {
					t.Fatalf("expired recovery created evidence: %v", err)
				}
				return
			}
			err = j.Recover(cmd.Context())
			wantSuccess := scenario == "healthy" || scenario == "stopped-orphan" || scenario == "missing-parent" || scenario == "interrupted" || scenario == "expired"
			if (err == nil) != wantSuccess {
				t.Fatalf("scenario=%s err=%v", scenario, err)
			}
			if scenario == "interrupted" && journal.receipt.RecoveryEvidence == "" {
				t.Fatal("missing durable recovery evidence binding")
			}
			if scenario == "stopped-orphan" {
				matches, e := filepath.Glob(socket + ".upgrade-orphan-*")
				if e != nil || len(matches) != 1 {
					t.Fatalf("quarantine evidence: %v %v", matches, e)
				}
				if e = j.Recover(cmd.Context()); e != nil {
					t.Fatalf("resume: %v", e)
				}
			}
			if wantSuccess && authoritybadger.Inspect(context.Background(), root).State != authoritybadger.StateReady {
				t.Fatal("authority not closed/qualified")
			}
		})
	}
}
